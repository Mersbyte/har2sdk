/** OpenAPI 3.1 emitter, sharing the plan (and named schemas) with the TS SDK. */
import { VERSION } from "./codegen.js";
import { trimTrailingSlashes } from "./linear.js";
import type { Plan, PlannedOp } from "./plan.js";
import { namedToJsonSchema, toJsonSchema, type JsonSchema } from "./types.js";

export interface OpenApiOptions {
  /** Include redacted request/response examples (default false). */
  examples?: boolean;
  title?: string;
}

export function generateOpenApi(plan: Plan, opts: OpenApiOptions = {}): Record<string, unknown> {
  const { model, registry, ops } = plan;
  const schemas: Record<string, JsonSchema> = {};
  for (const nt of registry.types) schemas[nt.name] = namedToJsonSchema(nt);

  const paths: Record<string, Record<string, unknown>> = {};
  const restOps = ops.filter((o) => !o.ep.graphql && !o.ep.rpc);
  const gqlOps = ops.filter((o) => o.ep.graphql);

  for (const op of restOps) {
    const item = (paths[op.ep.path] ??= {});
    item[op.ep.method.toLowerCase()] = restOperation(op, opts);
  }

  // tRPC procedures each get their own path: /api/trpc/user.byId
  for (const op of ops.filter((o) => o.ep.rpc?.kind === "trpc")) {
    const path = trimTrailingSlashes(op.ep.path) + "/" + op.ep.rpc!.procedure;
    const item = (paths[path] ??= {});
    item[op.ep.method.toLowerCase()] = trpcOperation(op);
  }

  // JSON-RPC methods share one URL: one operation, one body variant per method.
  const rpcGroups = new Map<string, PlannedOp[]>();
  for (const op of ops.filter((o) => o.ep.rpc?.kind === "jsonrpc")) {
    const key = `${op.ep.origin} ${op.ep.method} ${op.ep.path}`;
    rpcGroups.set(key, [...(rpcGroups.get(key) ?? []), op]);
  }
  let rpcIndex = 0;
  for (const group of rpcGroups.values()) {
    const first = group[0]!.ep;
    const item = (paths[first.path] ??= {});
    item[first.method.toLowerCase()] = jsonRpcOperation(group, rpcIndex++ === 0 ? "jsonRpc" : `jsonRpc${rpcIndex}`);
  }

  // All GraphQL operations on one path+method become a single OpenAPI operation.
  const gqlGroups = new Map<string, PlannedOp[]>();
  for (const op of gqlOps) {
    const key = `${op.ep.origin} ${op.ep.method} ${op.ep.path}`;
    gqlGroups.set(key, [...(gqlGroups.get(key) ?? []), op]);
  }
  let gqlIndex = 0;
  for (const group of gqlGroups.values()) {
    const first = group[0]!.ep;
    const item = (paths[first.path] ??= {});
    item[first.method.toLowerCase()] = graphqlOperation(group, gqlIndex++ === 0 ? "graphql" : `graphql${gqlIndex}`);
  }

  const securitySchemes: Record<string, unknown> = {};
  const a = model.auth;
  if (a.bearer && /^bearer$/i.test(a.tokenScheme)) securitySchemes.bearerAuth = { type: "http", scheme: "bearer", ...(a.bearerIsJwt ? { bearerFormat: "JWT" } : {}) };
  else if (a.bearer) securitySchemes.tokenAuth = { type: "apiKey", in: "header", name: "Authorization", description: `\`${a.tokenScheme ? a.tokenScheme + " " : ""}<token>\`` };
  if (a.basic) securitySchemes.basicAuth = { type: "http", scheme: "basic" };
  if (a.apiKeyHeaders[0]) securitySchemes.apiKeyHeader = { type: "apiKey", in: "header", name: a.apiKeyHeaders[0] };
  if (a.apiKeyQuery[0]) securitySchemes.apiKeyQuery = { type: "apiKey", in: "query", name: a.apiKeyQuery[0] };
  if (a.cookieNames[0]) securitySchemes.cookieAuth = { type: "apiKey", in: "cookie", name: a.cookieNames[0] };

  const tags = [...new Set(ops.map((o) => o.ep.tag))].sort().map((name) => ({ name }));
  const doc: Record<string, unknown> = {
    openapi: "3.1.0",
    info: {
      title: opts.title ?? plan.clientName.replace(/Client$/, "") + " API (reverse-engineered)",
      version: "0.0.0",
      description:
        // The capture's file name is not written: it often names a person ("oguz-bank.har").
        `Generated by har2sdk v${VERSION} — ${ops.length} endpoints observed in ${model.stats.kept} requests. ` +
        `Schemas describe observed traffic, not a published contract.`,
    },
    servers: plan.baseUrl ? [{ url: plan.baseUrl }] : [],
    tags,
    paths,
    components: { schemas, ...(Object.keys(securitySchemes).length ? { securitySchemes } : {}) },
  };
  if (Object.keys(securitySchemes).length) doc.security = Object.keys(securitySchemes).map((k) => ({ [k]: [] }));
  return doc;
}

function restOperation(op: PlannedOp, opts: OpenApiOptions): Record<string, unknown> {
  const { ep } = op;
  const parameters = [
    ...op.pathParams.map((p) => ({
      name: p.wire,
      in: "path",
      required: true,
      schema: toJsonSchema(p.type),
      ...(opts.examples && p.examples[0] && p.examples[0] !== "<redacted>" ? { example: p.examples[0] } : {}),
    })),
    ...op.queryParams.map((q) => ({
      name: q.wire,
      in: "query",
      required: q.required,
      schema: toJsonSchema(q.type),
      ...(q.type.k === "array" ? { style: "form", explode: true } : {}),
      ...(opts.examples && q.examples[0] && q.examples[0] !== "<redacted>" ? { example: q.examples[0] } : {}),
    })),
  ];

  const operation: Record<string, unknown> = {
    operationId: ep.name,
    tags: [ep.tag],
    summary: ep.description?.split(/(?<=\.)\s/)[0] ?? `${ep.method} ${ep.path}`,
    ...(ep.description ? { description: ep.description } : {}),
    ...(parameters.length ? { parameters } : {}),
  };
  if (op.foreignOrigin) operation.servers = [{ url: op.foreignOrigin }];

  if (op.body) {
    const mime = op.body.kind === "json" ? "application/json" : op.body.mimeType.split(";")[0] || "application/octet-stream";
    const schema = op.body.kind === "multipart" ? { type: "object" } : toJsonSchema(op.body.type);
    const content: Record<string, unknown> = { schema };
    if (opts.examples && ep.example?.requestBody !== undefined) content.example = ep.example.requestBody;
    operation.requestBody = { required: true, content: { [mime]: content } };
  }

  const responses: Record<string, unknown> = {};
  for (const r of ep.responses) {
    const key = r.status ? String(r.status) : "default";
    const res: Record<string, unknown> = { description: `Observed ${r.count}×` };
    if (r.kind === "json") {
      const isOk = r.status >= 200 && r.status < 300;
      const node = isOk ? (op.response.byStatus?.get(r.status) ?? op.response.type) : (op.error?.byStatus?.get(r.status) ?? op.error?.type);
      const schema = node ? toJsonSchema(node) : {};
      const content: Record<string, unknown> = { schema };
      if (opts.examples && ep.example && ep.example.status === r.status && ep.example.responseBody !== undefined) content.example = ep.example.responseBody;
      res.content = { "application/json": content };
    } else if (r.kind === "text" && r.mimeType) {
      res.content = { [r.mimeType.split(";")[0]!]: { schema: { type: "string" } } };
    }
    responses[key] = res;
  }
  operation.responses = Object.keys(responses).length ? responses : { default: { description: "No response recorded" } };
  operation["x-har2sdk"] = { observed: ep.count };
  return operation;
}

function trpcOperation(op: PlannedOp): Record<string, unknown> {
  const r = op.ep.rpc!;
  const wrap = (s: JsonSchema): JsonSchema => (r.superjson ? { type: "object", properties: { json: s }, required: ["json"] } : s);
  const input = op.body ? wrap(toJsonSchema(op.body.type)) : undefined;
  const operation: Record<string, unknown> = {
    operationId: op.ep.name,
    tags: [op.ep.tag],
    summary: op.ep.description?.split(/(?<=\.)\s/)[0] ?? `tRPC ${r.viaGet ? "query" : "mutation"} ${r.procedure}`,
    ...(op.ep.description ? { description: op.ep.description } : {}),
  };
  if (r.viaGet && input) {
    operation.parameters = [{ name: "input", in: "query", required: false, description: "JSON-encoded input", content: { "application/json": { schema: input } } }];
  } else if (input) {
    operation.requestBody = { required: true, content: { "application/json": { schema: input } } };
  }
  operation.responses = {
    "200": {
      description: `Observed ${op.ep.count}×`,
      content: {
        "application/json": {
          schema: { type: "object", properties: { result: { type: "object", properties: { data: wrap(toJsonSchema(op.response.type)) } } } },
        },
      },
    },
  };
  operation["x-trpc-procedure"] = r.procedure;
  return operation;
}

function jsonRpcOperation(group: PlannedOp[], operationId: string): Record<string, unknown> {
  const variants = group.map((op) => ({
    type: "object",
    title: op.ep.rpc!.procedure,
    properties: {
      jsonrpc: { const: "2.0" },
      id: { type: ["integer", "string"] },
      method: { const: op.ep.rpc!.procedure },
      ...(op.body ? { params: toJsonSchema(op.body.type) } : {}),
    },
    required: ["jsonrpc", "method"],
  }));
  const results = group.map((op) => toJsonSchema(op.response.type));
  return {
    operationId,
    tags: ["rpc"],
    summary: `JSON-RPC endpoint (${group.length} method${group.length === 1 ? "" : "s"} observed)`,
    description: group.map((op) => `- \`${op.ep.rpc!.procedure}\` → SDK method \`${op.ep.name}()\``).join("\n"),
    requestBody: { required: true, content: { "application/json": { schema: variants.length === 1 ? variants[0] : { oneOf: variants } } } },
    responses: {
      "200": {
        description: "JSON-RPC response",
        content: {
          "application/json": {
            schema: {
              type: "object",
              properties: { jsonrpc: { const: "2.0" }, id: {}, result: results.length === 1 ? results[0] : { anyOf: results }, error: { type: "object" } },
            },
          },
        },
      },
    },
    "x-jsonrpc-methods": group.map((op) => ({ method: op.ep.rpc!.procedure, sdkMethod: op.ep.name })),
  };
}

function graphqlOperation(group: PlannedOp[], operationId: string): Record<string, unknown> {
  const variants = group.map((op) => ({
    type: "object",
    title: op.ep.graphql!.operationName,
    properties: {
      ...(op.ep.graphql!.anonymous ? {} : { operationName: { const: op.ep.graphql!.operationName } }),
      ...(op.ep.graphql!.query ? { query: { type: "string" } } : {}),
      variables: op.body ? toJsonSchema(op.body.type) : { type: "object" },
    },
    required: op.ep.graphql!.anonymous ? ["query"] : ["operationName"],
  }));
  const data = group.map((op) => toJsonSchema(op.response.type));
  return {
    operationId,
    tags: ["graphql"],
    summary: `GraphQL endpoint (${group.length} operation${group.length === 1 ? "" : "s"} observed)`,
    description: group.map((op) => `- \`${op.ep.graphql!.operationName}\` (${op.ep.graphql!.operationType}) → SDK method \`${op.ep.name}()\``).join("\n"),
    requestBody: { required: true, content: { "application/json": { schema: variants.length === 1 ? variants[0] : { oneOf: variants } } } },
    responses: {
      "200": {
        description: "GraphQL response",
        content: {
          "application/json": {
            schema: { type: "object", properties: { data: data.length === 1 ? data[0] : { anyOf: data }, errors: { type: "array" } } },
          },
        },
      },
    },
    "x-graphql-operations": group.map((op) => ({
      operationName: op.ep.graphql!.operationName,
      operationType: op.ep.graphql!.operationType,
      sdkMethod: op.ep.name,
      ...(op.ep.graphql!.query ? { query: op.ep.graphql!.query } : {}),
      ...(op.ep.graphql!.persistedHash ? { persistedQueryHash: op.ep.graphql!.persistedHash } : {}),
    })),
    "x-har2sdk": { observed: group.reduce((n, op) => n + op.ep.count, 0) },
  };
}
